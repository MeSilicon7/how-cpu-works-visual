/**
 * An 8×8 bitmap font. Every character is 8 rows of 8 pixels, and every row is ONE byte:
 * bit 7 (value 128) is the leftmost pixel, bit 0 (value 1) the rightmost, and 1 = ink.
 *
 * Codes 0–127 (ASCII) use the classic IBM PC 8×8 design, taken from Daniel Hepper's
 * public-domain "font8x8_basic" (itself based on Marcel Sondaar's public-domain font and
 * IBM's VGA font). That file stores bit 0 as the leftmost pixel, so every row here is
 * mirrored. The Cyrillic letters (for the Russian keyboard layout) and the picture
 * glyphs were drawn for this book in the same style.
 *
 * The ASCII part is one flat table, exactly like a font in ROM: the glyph for code c
 * starts at byte c × 8. For 'A' (65) that is byte 520: 30 78 CC CC FC CC CC 00.
 */

