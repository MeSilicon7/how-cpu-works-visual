export const MISSING_GLYPH = [0xfe, 0x82, 0x82, 0x82, 0x82, 0x82, 0xfe, 0x00];

/** The 8 row bytes for a Unicode code point, or null if this font has no glyph for it. */
export function glyph8(code: number): number[] | null {
  if (code >= 32 && code < 127) return Array.from(FONT8.subarray(code * 8, code * 8 + 8));
  const ch = String.fromCodePoint(code);
  const latin = SAME_AS_LATIN[ch];
  if (latin) return glyph8(latin.charCodeAt(0));
  return CYRILLIC[ch] ?? null;
}

/** A "bold" version: smear every row one pixel to the right (row OR row ÷ 2). */
export function boldRows(rows: number[]): number[] {
  return rows.map((r) => (r | (r >> 1)) & 0xff);
}

/** The picture the made-up picture font stores at a code: picture number code mod 8. */
export function pictureFor(code: number) {
  return PICTURES[code % PICTURES.length];
}

/** Turn 8 row bytes into an 8×8 grid of 0/1, top row first, leftmost pixel first. */
export function rowsToGrid(rows: number[]): number[][] {
  return rows.map((r) => Array.from({ length: 8 }, (_, x) => (r >> (7 - x)) & 1));
}
