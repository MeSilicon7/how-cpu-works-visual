/** A classic 5×7 pixel font (rows top→bottom, 5 bits each, MSB = leftmost pixel). */
const glyphs: Record<string, string[]> = {
  "0": ["01110", "10001", "10011", "10101", "11001", "10001", "01110"],
  "1": ["00100", "01100", "00100", "00100", "00100", "00100", "01110"],
  "2": ["01110", "10001", "00001", "00010", "00100", "01000", "11111"],
  "3": ["11111", "00010", "00100", "00010", "00001", "10001", "01110"],
  "4": ["00010", "00110", "01010", "10010", "11111", "00010", "00010"],
  "5": ["11111", "10000", "11110", "00001", "00001", "10001", "01110"],
  "6": ["00110", "01000", "10000", "11110", "10001", "10001", "01110"],
  "7": ["11111", "00001", "00010", "00100", "01000", "01000", "01000"],
  "8": ["01110", "10001", "10001", "01110", "10001", "10001", "01110"],
  "9": ["01110", "10001", "10001", "01111", "00001", "00010", "01100"],
  "+": ["00000", "00100", "00100", "11111", "00100", "00100", "00000"],
  "-": ["00000", "00000", "00000", "11111", "00000", "00000", "00000"],
  "=": ["00000", "00000", "11111", "00000", "11111", "00000", "00000"],
  h: ["10000", "10000", "10110", "11001", "10001", "10001", "10001"],
  i: ["00100", "00000", "01100", "00100", "00100", "00100", "01110"],
  H: ["10001", "10001", "10001", "11111", "10001", "10001", "10001"],
  " ": ["00000", "00000", "00000", "00000", "00000", "00000", "00000"],
  "!": ["00100", "00100", "00100", "00100", "00100", "00000", "00100"],
};

export function glyph(ch: string): number[][] {
  const g = glyphs[ch] ?? glyphs[" "];
  return g.map((row) => row.split("").map(Number));
}

/** Render a string into a pixel grid (1 = lit). Each glyph is 5 wide plus 1 column of spacing. */
export function renderText(text: string, padX = 1, padY = 1) {
  const w = text.length * 6 - 1 + padX * 2;
  const h = 7 + padY * 2;
  const grid = Array.from({ length: h }, () => new Array(w).fill(0));
  const owner = Array.from({ length: h }, () => new Array(w).fill(-1));
  [...text].forEach((ch, ci) => {
    const g = glyph(ch);
    g.forEach((row, y) =>
      row.forEach((v, x) => {
        const gx = padX + ci * 6 + x;
        const gy = padY + y;
        grid[gy][gx] = v;
        owner[gy][gx] = ci;
      }),
    );
  });
  return { grid, owner, w, h };
}
